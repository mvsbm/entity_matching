"""What a step asks of an engine, whichever runs its SQL: DuckDB on this machine (er.engine.duckdb), or BigQuery.

    run(sql)            a statement; nothing comes back
    value(sql)          the first row's first value          row(sql)    the first row      first(sql)  the first row or None
    rows(sql)           every row, as tuples                 frame(sql)  a pandas frame     numpy(sql)  each column as an array
    arrow(sql)          an Arrow table                       batches(sql, rows)  Arrow batches as they come
    register(name, x)   a frame or an Arrow table SQL reads by `name`, until unregister(name)
    view(name, sql)     `sql` read by `name`, computed when read, until unregister(name)
    cursor()            the same database for another thread
    close()

frame, numpy, arrow and rows are for small results (a sample, a count per level, a review sheet), or results read
in chunks through batches: no step pulls a table that grows with the records into Python whole.
"""
from typing import Protocol

from er.engine.duckdb import DuckDB


class Engine(Protocol):  # DuckDB's verbs: the BigQuery engine gives the same
    name: str

    def run(self, sql: str, params: list | None = None) -> None: ...
    def value(self, sql: str, params: list | None = None) -> object: ...
    def row(self, sql: str, params: list | None = None) -> tuple: ...
    def first(self, sql: str, params: list | None = None) -> tuple | None: ...
    def rows(self, sql: str, params: list | None = None) -> list[tuple]: ...
    def frame(self, sql: str, params: list | None = None): ...
    def numpy(self, sql: str, params: list | None = None) -> dict: ...
    def arrow(self, sql: str, params: list | None = None): ...
    def batches(self, sql: str, rows: int): ...
    def register(self, name: str, data: object) -> None: ...
    def unregister(self, name: str) -> None: ...
    def view(self, name: str, sql: str) -> None: ...
    def cursor(self) -> "Engine": ...
    def close(self) -> None: ...


__all__ = ["DuckDB", "Engine"]
