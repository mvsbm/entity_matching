"""What a step asks of an engine, whichever runs its SQL: DuckDB on this machine (er.engine.duckdb), or BigQuery.

    run(sql)            a statement; nothing comes back
    value(sql)          the first row's first value          row(sql)    the first row
    rows(sql)           every row, as tuples                 frame(sql)  a pandas frame     numpy(sql)  each column as an array
    batches(sql, rows)  Arrow batches as they come
    register(name, x)   a frame or an Arrow table SQL reads by `name`, until unregister(name)
    view(name, sql)     `sql` read by `name`, computed when read, until unregister(name)
    cursor()            the same database for another thread
    room()              the bytes a step's tables may take (spill_room: of those, the disk's)
    close()

and where a step's tables and files are, so its SQL holds no part only one engine has:

    columns(x)          a table's or a query's columns: (name, type)       exists(table)   whether it is there
    read(files, …)      Parquet files as a relation SQL reads              write(sql, dest)  rows written as a file
    slices(table, size) conditions that each hold one slice of its rows    threads(), memory()  the engine's limits
    attach(alias, path) a database SQL reads as alias.table, until detach(alias)

frame, numpy and rows are for small results (a sample, a count per level, a lookup's candidates), or results read
in chunks through batches: no step pulls a table that grows with the records into Python whole.
"""
from typing import Protocol

from er.engine.duckdb import DuckDB


class Engine(Protocol):  # DuckDB's verbs: the BigQuery engine gives the same
    name: str

    def run(self, sql: str, params: list | None = None) -> None: ...
    def value(self, sql: str, params: list | None = None) -> object: ...
    def row(self, sql: str, params: list | None = None) -> tuple: ...
    def rows(self, sql: str, params: list | None = None) -> list[tuple]: ...
    def frame(self, sql: str, params: list | None = None): ...
    def numpy(self, sql: str, params: list | None = None) -> dict: ...
    def batches(self, sql: str, rows: int): ...
    def register(self, name: str, data: object) -> None: ...
    def unregister(self, name: str) -> None: ...
    def view(self, name: str, sql: str) -> None: ...
    def cursor(self) -> "Engine": ...
    def room(self) -> float: ...
    def spill_room(self) -> float: ...
    def close(self) -> None: ...
    def columns(self, x: str) -> list[tuple[str, str]]: ...
    def exists(self, table: str) -> bool: ...
    def read(self, files, *, by_name: bool = False, filename: bool = False, row_numbers: bool = False) -> str: ...
    def write(self, sql: str, dest, compression: str | None = None) -> None: ...
    def threads(self) -> int: ...
    def memory(self) -> str: ...
    def slices(self, table: str, size: int, n: int | None = None) -> list[str]: ...
    def attach(self, alias: str, path, read_only: bool = False, row_group_size: int | None = None) -> None: ...
    def detach(self, alias: str) -> None: ...


__all__ = ["DuckDB", "Engine"]
